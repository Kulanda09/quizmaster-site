function stagger(subject: Subject, offset: number): Subject {
  return {
    ...subject,
    questions: subject.questions.map((question, index) => {
      const shift = (index + offset) % 4;
      if (shift === 0) return question;
      const options = [0, 1, 2, 3].map(
        (slot) => question.options[(slot - shift + 4) % 4],
      ) as Question["options"];
      const correct = ((question.correct + shift) % 4) as Question["correct"];
      return { ...question, options, correct };
    }),
  };
}

export const SUBJECTS: Subject[] = RAW_SUBJECTS.map((subject, subjectIndex) =>
  stagger(subject, subjectIndex),
);

export function getSubject(id: string): Subject | undefined {
  return SUBJECTS.find((s) => s.id === id);
}
